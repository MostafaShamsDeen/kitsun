// Bridge between the Kitsun window and the main process.
const { contextBridge, ipcRenderer } = require('electron');

contextBridge.exposeInMainWorld('kitsun', {
  getState: () => ipcRenderer.invoke('state:get'),
  showAccount: (id) => ipcRenderer.invoke('ui:show-account', id),
  setSplit: (split) => ipcRenderer.invoke('ui:split', split),
  setLayout: (name) => ipcRenderer.invoke('ui:layout', name),
  setPaneRatios: (ratios) => ipcRenderer.invoke('ui:ratios', ratios),
  focusPane: (p) => ipcRenderer.invoke('ui:focus-pane', p),
  goHome: () => ipcRenderer.invoke('ui:home'),
  getStats: () => ipcRenderer.invoke('stats:get'),
  onStatsUpdated: (fn) => ipcRenderer.on('stats-updated', () => fn()),
  getSessions: () => ipcRenderer.invoke('sessions:get'),
  onSessions: (fn) => ipcRenderer.on('sessions', (_e, s) => fn(s)),
  searchSessions: (text) => ipcRenderer.invoke('search:query', text),
  openSession: (id, sessionId) => ipcRenderer.invoke('search:open', id, sessionId),
  onOpenSwitcher: (fn) => ipcRenderer.on('open-switcher', () => fn()),
  startHandoff: (req) => ipcRenderer.invoke('handoff:start', req),
  restartForHandoff: (id, sessionId) => ipcRenderer.invoke('handoff:restart', id, sessionId),
  getChrome: () => ipcRenderer.invoke('chrome:get'),
  openChrome: (id) => ipcRenderer.invoke('chrome:open', id),
  onChrome: (fn) => ipcRenderer.on('chrome', (_e, c) => fn(c)),
  startAccount: (id) => ipcRenderer.invoke('account:start', id),
  stopAccount: (id, force) => ipcRenderer.invoke('account:stop', id, force === true),
  waitForAccount: (id) => ipcRenderer.invoke('account:wait', id),
  restartFrozen: (id) => ipcRenderer.invoke('account:restart-frozen', id),
  stopFrozen: (id) => ipcRenderer.invoke('account:stop-frozen', id),
  onNotice: (fn) => ipcRenderer.on('notice', (_e, n) => fn(n)),
  onRequestStop: (fn) => ipcRenderer.on('request-stop', (_e, id) => fn(id)),
  restartHere: (id) => ipcRenderer.invoke('account:restart-here', id),
  saveAccount: (account) => ipcRenderer.invoke('account:save', account),
  removeAccount: (id) => ipcRenderer.invoke('account:remove', id),
  finishSignIn: (id, link) => ipcRenderer.invoke('account:sign-in-link', id, link),
  sendPaneRects: (rects) => ipcRenderer.send('panes:rects', rects),
  setOverlay: (hidden) => ipcRenderer.send('overlay', hidden),
  getSettings: () => ipcRenderer.invoke('settings:get'),
  setSettings: (changes) => ipcRenderer.invoke('settings:set', changes),
  onOpenSettings: (fn) => ipcRenderer.on('open-settings', () => fn()),
  onStatus: (fn) => ipcRenderer.on('status', (_e, s) => fn(s)),
  onUi: (fn) => ipcRenderer.on('ui', (_e, ui) => fn(ui)),
  getCatalog: (fresh) => ipcRenderer.invoke('catalog:get', fresh === true),
  getIt: (id) => ipcRenderer.invoke('catalog:get-it', id),
  pickApp: () => ipcRenderer.invoke('app:pick'),
});
